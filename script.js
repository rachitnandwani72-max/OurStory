function getWheelAudioContext() {
  if (!wheelAudioContext) {
    const AudioContextClass = window.AudioContext || window.webkitAudioContext;
    if (!AudioContextClass) return null;
    wheelAudioContext = new AudioContextClass();
  }
  if (wheelAudioContext.state === "suspended") wheelAudioContext.resume().catch(() => {});
  return wheelAudioContext;
}

function playWheelTick(intensity = 1) {
  const ctx = getWheelAudioContext();
  if (!ctx) return;
  const now = ctx.currentTime;
  const bufferSize = Math.max(1, Math.floor(ctx.sampleRate * 0.045));
  const buffer = ctx.createBuffer(1, bufferSize, ctx.sampleRate);
  const data = buffer.getChannelData(0);
  for (let i = 0; i < bufferSize; i++) {
    const decay = Math.pow(1 - i / bufferSize, 4);
    data[i] = (Math.random() * 2 - 1) * decay;
  }
  const source = ctx.createBufferSource();
  const gain = ctx.createGain();
  const lowpass = ctx.createBiquadFilter();
  const highpass = ctx.createBiquadFilter();
  source.buffer = buffer;
  lowpass.type = "lowpass";
  lowpass.frequency.setValueAtTime(2200, now);
  lowpass.Q.setValueAtTime(.7, now);
  highpass.type = "highpass";
  highpass.frequency.setValueAtTime(360, now);
  gain.gain.setValueAtTime(0.0001, now);
  gain.gain.exponentialRampToValueAtTime(0.032 * intensity, now + 0.004);
  gain.gain.exponentialRampToValueAtTime(0.0001, now + 0.05);
  source.connect(lowpass);
  lowpass.connect(highpass);
  highpass.connect(gain);
  gain.connect(ctx.destination);
  source.start(now);
  source.stop(now + 0.052);
}

