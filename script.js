function createParticleBurst(x, y, count = 24) {
  for (let i = 0; i < count; i++) {
    const particle = document.createElement("span");
    const angle = (Math.PI * 2 * i) / count + Math.random() * .25;
    const distance = 55 + Math.random() * 125;
    particle.className = "particle-burst";
    particle.textContent = i % 3 === 0 ? "♥" : "✦";
    particle.style.left = `${x}px`;
    particle.style.top = `${y}px`;
    particle.style.setProperty("--burst-x", `${Math.cos(angle) * distance}px`);
    particle.style.setProperty("--burst-y", `${Math.sin(angle) * distance}px`);
    particle.style.setProperty("--burst-r", `${Math.random() * 160 - 80}deg`);
    particle.style.animationDelay = `${Math.random() * .12}s`;
    document.body.appendChild(particle);
    setTimeout(() => particle.remove(), 1500);
  }
}

let reasonsProgressRaf = 0;
let reasonsSparkleAt = 0;
function setupReasonsProgress() {
  const section = document.querySelector(".reasons-screen");
  const grid = document.getElementById("reasonsGrid");
  const line = grid?.querySelector(".reasons-progress-line");
  if (!section || !grid || !line || line.dataset.ready) return;
  line.dataset.ready = "true";
  const update = () => {
    reasonsProgressRaf = 0;
    if (!section.classList.contains("active")) return;
    const rect = grid.getBoundingClientRect();
    const viewport = window.innerHeight || document.documentElement.clientHeight;
    const scrollable = Math.max(rect.height - viewport * .42, 1);
    const progress = Math.min(1, Math.max(0, (viewport * .48 - rect.top) / scrollable));
    grid.style.setProperty("--reasons-progress", progress.toFixed(4));
    if (progress > .03 && progress < .98 && Math.abs(progress - reasonsSparkleAt) > .055) {
      reasonsSparkleAt = progress;
      const sparkle = document.createElement("em");
      sparkle.className = "reasons-progress-sparkle";
      sparkle.style.top = `${progress * 100}%`;
      line.appendChild(sparkle);
      setTimeout(() => sparkle.remove(), 850);
    }
  };
  const requestUpdate = () => {
    if (!reasonsProgressRaf) reasonsProgressRaf = requestAnimationFrame(update);
  };
  window.addEventListener("scroll", requestUpdate, {passive:true});
  window.addEventListener("resize", requestUpdate, {passive:true});
  requestUpdate();
}

document.addEventListener("click", event => {
  const hiddenAudioToggle = event.target.closest("[data-hidden-audio-toggle]");
  if (hiddenAudioToggle) {
    const card = hiddenAudioToggle.closest("[data-hidden-audio-card]");
    const audio = document.getElementById("hiddenVoiceAudio");
    if (!audio || !card) return;
    if (audio.paused) {
      audio.currentTime = audio.currentTime || 0;
      duckBackgroundForHiddenVoice();
      audio.play().then(() => {
        card.classList.add("is-playing");
        hiddenAudioToggle.setAttribute("aria-pressed","true");
      }).catch(() => {
        card.classList.remove("is-playing");
        hiddenAudioToggle.setAttribute("aria-pressed","false");
      });
    } else {
      audio.pause();
      restoreBackgroundAfterHiddenVoice();
      card.classList.remove("is-playing");
      hiddenAudioToggle.setAttribute("aria-pressed","false");
    }
    return;
  }
  const introToggle = event.target.closest("[data-intro-voice-toggle]");
  if (introToggle) {
    toggleIntroVoiceNote();
    return;
  }
  const finalToggle = event.target.closest("[data-final-voice-toggle]");
  if (finalToggle) {
    toggleFinalVoiceNote();
    return;
  }
  const toggle = event.target.closest("[data-voice-toggle]");
  if (!toggle) return;
  const card = toggle.closest("[data-voice-card]");
  const wasPlaying = card.classList.contains("is-playing");
  card.classList.toggle("is-playing", !wasPlaying);
  card.classList.toggle("is-paused", wasPlaying);
  toggle.setAttribute("aria-pressed", String(!wasPlaying));
});

