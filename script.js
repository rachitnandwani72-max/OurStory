function setupMainMusicLoop() {
  mainWebsiteMusic.loop = true;
  mainWebsiteMusic.preload = "auto";
  letterMusic.loop = true;
  letterMusic.preload = "auto";
  introVoiceNote.preload = "auto";
  finalThankYouVoiceNote.preload = "auto";
  mainWebsiteMusic.load();
  letterMusic.load();
  introVoiceNote.load();
  finalThankYouVoiceNote.load();
  mainWebsiteMusic.addEventListener("ended", () => {
    if (mainMusicEndedForLetter) return;
    mainWebsiteMusic.currentTime = 0;
    mainWebsiteMusic.play().catch(() => {});
  });
  mainWebsiteMusic.addEventListener("timeupdate", () => {
    if (mainMusicEndedForLetter || mainWebsiteMusic.paused || !Number.isFinite(mainWebsiteMusic.duration)) return;
    if (mainWebsiteMusic.duration - mainWebsiteMusic.currentTime <= mainMusicLoopGuardSeconds) {
      mainWebsiteMusic.currentTime = 0;
      mainWebsiteMusic.play().catch(() => {});
    }
  });
  mainWebsiteMusic.addEventListener("waiting", () => {
    if (mainMusicEndedForLetter || !Number.isFinite(mainWebsiteMusic.duration)) return;
    if (mainWebsiteMusic.duration - mainWebsiteMusic.currentTime <= 1) {
      mainWebsiteMusic.currentTime = 0;
      mainWebsiteMusic.play().catch(() => {});
    }
  });
}

