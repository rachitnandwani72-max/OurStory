function getSyncedTranscriptEntries(timeline, audio, currentTime, durationHint) {
  const lastTime = timeline.at(-1)?.time || 1;
  const duration = Number.isFinite(audio.duration) && audio.duration > 0 ? audio.duration : durationHint;
  const targetEnd = Math.max(lastTime, duration - 0.45);
  const scale = Math.abs(targetEnd - lastTime) > 1.4 ? targetEnd / lastTime : 1;
  return timeline.filter(entry => currentTime >= entry.time * scale);
}

