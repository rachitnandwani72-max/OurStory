function animateWheelSpin(fromRotation, toRotation, onComplete, duration = 5800) {
  cancelAnimationFrame(wheelTickerFrame);
  const segment = 360 / wheelRewards.length;
  const start = performance.now();
  let lastMarker = Math.floor(fromRotation / segment);
  const ease = progress => 1 - Math.pow(1 - progress, 4);
  const frame = now => {
    const progress = Math.min(1, (now - start) / duration);
    const eased = ease(progress);
    const currentRotation = fromRotation + (toRotation - fromRotation) * eased;
    setWheelRotation(currentRotation);
    const marker = Math.floor(currentRotation / segment);
    if (marker > lastMarker) {
      const passed = Math.min(marker - lastMarker, 3);
      for (let i = 0; i < passed; i++) playWheelTick(Math.max(.38, 1 - progress * .5));
      lastMarker = marker;
    }
    if (progress < 1) {
      wheelTickerFrame = requestAnimationFrame(frame);
    } else {
      setWheelRotation(toRotation);
      playWheelTick(.48);
      onComplete();
    }
  };
  wheelTickerFrame = requestAnimationFrame(frame);
}

