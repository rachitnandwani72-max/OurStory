function spawnHeart() {
  if (state.heartLives <= 0 || state.heartScore >= 21) return;
  const arena = document.getElementById("heartArena");
  const heart = document.createElement("span");
  heart.className = "falling-heart"; heart.textContent = "♡";
  const x = 10 + Math.random() * (arena.clientWidth - 55);
  const duration = Math.max(1450, 2700 - state.heartScore * 70);
  heart.style.left = `${x}px`; arena.appendChild(heart);
  const start = performance.now();
  function fall(now) {
    if (!heart.isConnected) return;
    const progress = (now - start) / duration;
    const y = progress * (arena.clientHeight - 45);
    heart.style.transform = `translateY(${y}px) rotate(${progress * 50}deg)`;
    const catcher = document.getElementById("heartCatcher").getBoundingClientRect();
    const box = heart.getBoundingClientRect();
    if (box.bottom >= catcher.top && box.left < catcher.right && box.right > catcher.left) {
      showScoreFloat(box.left - arena.getBoundingClientRect().left, box.top - arena.getBoundingClientRect().top);
      heart.remove(); state.heartScore++;
      document.getElementById("heartScore").textContent = state.heartScore;
      if (state.heartScore >= 21) winHearts();
      return;
    }
    if (progress >= 1) {
      heart.remove(); state.heartLives--;
      document.getElementById("heartLives").textContent = Array(state.heartLives).fill("♡").join(" ");
      if (state.heartLives <= 0) loseHearts();
      return;
    }
    requestAnimationFrame(fall);
  }
  requestAnimationFrame(fall);
}

